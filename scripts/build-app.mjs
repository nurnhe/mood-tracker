// Builds the installable app in docs/ (served by GitHub Pages) from index.html,
// which is the claude.ai artifact source. Run: node scripts/build-app.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const root = new URL("..", import.meta.url);
const page = readFileSync(new URL("index.html", root), "utf8");
const version = createHash("sha256").update(page).digest("hex").slice(0, 10);

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="theme-color" content="#f3f2f7" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#17151f" media="(prefers-color-scheme: dark)">
<meta name="description" content="A quick daily mood check-in with a month calendar colored by mood.">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" href="icon-192.png" type="image/png">
<link rel="apple-touch-icon" href="icon-192.png">
<style>:root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0;font-family:system-ui,sans-serif;font-size:14px}img{max-width:100%}[hidden]{display:none!important}</style>
<script>window.MOOD_APP_MODE = "app";</script>
</head>
<body>
${page}
<script>
if ("serviceWorker" in navigator) addEventListener("load", () => navigator.serviceWorker.register("sw.js").catch(() => {}));
</script>
</body>
</html>
`;
writeFileSync(new URL("docs/index.html", root), html);

const manifest = {
  name: "Daily Mood Log",
  short_name: "Mood Log",
  description: "A quick daily mood check-in with a month calendar colored by mood.",
  start_url: "./",
  scope: "./",
  display: "standalone",
  background_color: "#f3f2f7",
  theme_color: "#5b4bc4",
  icons: [
    { src: "icon-192.png", sizes: "192x192", type: "image/png" },
    { src: "icon-512.png", sizes: "512x512", type: "image/png" },
    { src: "icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
  ],
};
writeFileSync(new URL("docs/manifest.webmanifest", root), JSON.stringify(manifest, null, 2) + "\n");

const sw = `// Generated by scripts/build-app.mjs. Keeps the app working offline.
const CACHE = "mood-log-${version}";
const SHELL = ["./", "index.html", "manifest.webmanifest", "icon-192.png", "icon-512.png", "icon-maskable-512.png"];
self.addEventListener("install", (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting())); });
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  const url = new URL(e.request.url);
  const isFont = url.hostname === "fonts.googleapis.com" || url.hostname === "fonts.gstatic.com";
  if (url.origin !== location.origin && !isFont) return;
  if (e.request.mode === "navigate") {
    // Network first for the page so updates arrive; fall back to the cached copy offline.
    e.respondWith(fetch(e.request).then((r) => { const copy = r.clone(); caches.open(CACHE).then((c) => c.put("index.html", copy)); return r; }).catch(() => caches.match("index.html")));
    return;
  }
  e.respondWith(caches.match(e.request).then((hit) => hit || fetch(e.request).then((r) => {
    if (r.ok || r.type === "opaque") { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
    return r;
  })));
});
`;
writeFileSync(new URL("docs/sw.js", root), sw);
console.log("Built docs/ version", version);
